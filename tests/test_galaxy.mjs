import assert from 'node:assert/strict';
import {QualityController,Intro,handPhysics,Spring2D,nextPattern,usableFrame} from '../static/galaxy/logic.mjs';
const options={particle_count:100000,pixel_ratio:1.5,min_pixel_ratio:.75,low_fps:50,low_fps_s:3};
const quality=new QualityController(options);quality.frame(0);
for(let t=25;t<3000;t+=25)assert.equal(quality.frame(t),false);
assert.equal(quality.frame(3000),true);assert.equal(quality.particles,50000);
for(let t=3017;t<8000;t+=1000/60)quality.frame(t);
assert.equal(quality.particles,50000);assert.equal(quality.downgrades,1);
quality.frame(9000,false);assert.equal(quality.lowSince,null);
const lower=new QualityController({...options,particle_count:50000});lower.frame(0);
for(let t=25;t<=6000;t+=25)lower.frame(t);
assert.equal(lower.particles,50000);assert.ok(lower.ratio>=.75&&lower.ratio<1.5);
for(let t=6025;t<=15000;t+=25)lower.frame(t);
assert.equal(lower.ratio,.75);
const stable=new QualityController(options);stable.frame(0);
for(let t=1000/60;t<10000;t+=1000/60)stable.frame(t);
assert.equal(stable.downgrades,0);
const intro=new Intro(2);assert.equal(intro.interactive(9000),false);intro.begin(100);
assert.equal(intro.progress(1100),.5);assert.equal(intro.interactive(2099),false);assert.equal(intro.interactive(2100),true);
assert.equal(handPhysics({control:1,hands:[[.5,.5,0,0,0,0,-1]],distance:0}).collapse,1);
assert.equal(handPhysics({control:1,hands:[[.5,.5,1,0,0,0,1]],distance:0}).explode,1);
assert.equal(handPhysics({control:0,hands:[]}).scale,1);
assert.equal(nextPattern(3),0);assert.equal(nextPattern(0),1);
const spring=new Spring2D();for(let i=0;i<100;i++)spring.step([1,2],.016,2);
assert.ok(Math.abs(spring.p[1]-2)<1e-6);
assert.equal(usableFrame({viewport:2,capture_us:1000,completed_us:100000},2,10,400),true);
assert.equal(usableFrame({viewport:1,capture_us:1000,completed_us:1000},2,10,400),false);
assert.equal(usableFrame({viewport:2,capture_us:1000,completed_us:1000},2,401,400),false);
assert.equal(usableFrame({viewport:2,capture_us:1000,completed_us:401000},2,1,400),false);
console.log('galaxy intro gate, downgrade-only quality, hands, patterns and spring tests passed');
